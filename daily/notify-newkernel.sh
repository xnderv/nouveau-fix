#!/bin/bash
# Уведомление на рабочий стол. Запускается от имени пользователя (из обработчика ядра или из службы).
#   notify-newkernel.sh newkernel <версия>   — пришло новое ядро
#   notify-newkernel.sh notloaded <версия>   — после перезагрузки загружен не наш драйвер
# Кнопки в уведомлениях этот сервер уведомлений не поддерживает (проверено 21.10),
# поэтому в тексте — как найти значок «Драйвер видеокарты» в меню.
MODE="${1:-newkernel}"; V="${2:-}"
HOW="Нажми Super, набери «драйвер» и запусти «Драйвер видеокарты: подготовить под новое ядро»."
if [ "$MODE" = notloaded ]; then
    T="GTX 560 Ti: наш драйвер не загружен"
    B="Ядро $V работает со стандартным nouveau, частоты не управляются. $HOW Потом перезагрузись."
else
    T="GTX 560 Ti: пришло новое ядро $V"
    B="До перезагрузки подготовь драйвер под это ядро. $HOW"
fi
notify-send -a 'Драйвер видеокарты' -u critical -i video-display "$T" "$B"
