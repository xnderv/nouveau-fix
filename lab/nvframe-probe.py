#!/usr/bin/env python3
# ТОЛЬКО ЧТЕНИЕ (24.10, тест Б): регистры, которые драйвер NVIDIA ставит по уровню (запись 7), — у нас на текущем уровне
# рядом со значением NVIDIA. Рамка контроллера памяти и дисплея, хост-домен, 0x022680, PXBAR, запасные поля делителей,
# PTHERM CTRL_1. Порты тренировки памяти (0x10f918…) не читаются. Ничего не записывает.
# Запуск: sudo python3 ~/Home/nouveau-fix/lab/nvframe-probe.py УРОВЕНЬ(03|07|0f) [ФАЙЛ]
import mmap, os, struct, sys, glob, time

LV = sys.argv[1] if len(sys.argv) > 1 else '?'
# адрес, имя, значения NVIDIA на 03 / 07 / 0f (None — NVIDIA на этом уровне не пишет, значение не известно)
