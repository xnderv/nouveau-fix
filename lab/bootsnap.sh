#!/bin/bash
# Снимки регистров при загрузке (лабораторный драйвер с 25.10: строки «LAB boot snap #1 …» в журнале ядра — тактирование,
# PTHERM, датчик, GPIO/ШИМ; только чтение, до выбора первого уровня). Журнал ядра хранится на диске, так что снимок есть
# у каждой загрузки с этим драйвером.
#   bash ~/Home/nouveau-fix/lab/bootsnap.sh           — снимок текущей загрузки
#   bash ~/Home/nouveau-fix/lab/bootsnap.sh -3        — снимок загрузки -3 (номера: journalctl --list-boots)
#   bash ~/Home/nouveau-fix/lab/bootsnap.sh -3 0      — разница двух загрузок: регистр, значение в первой, во второй
#   bash ~/Home/nouveau-fix/lab/bootsnap.sh 0 results/bootsnap-…-bad.txt — разница текущей загрузки и сохранённого снимка
#   N=2 bash … — второй снимок загрузки (после выхода из сна), по умолчанию первый
# Датчик температуры (0x20008 — сырое значение, 0x20400 — °C) отличается всегда; итог считается и без него.
set -u
lines() {   # $1 = номер загрузки или файл → строки снимка
    if [ -f "$1" ]; then grep -E "LAB boot snap #${N:-1} " "$1"
    else journalctl -k -b "$1" -o cat --no-pager 2>/dev/null | grep -E "LAB boot snap #${N:-1} "; fi
}
snap() {    # → строки «регистр значение»
    lines "$1" | sed -E 's/.*LAB boot snap #[0-9]+ [^:]+://' | tr ' ' '\n' | grep '=' | tr '=' ' '
}
if [ $# -lt 2 ]; then
    b="${1:-0}"
    [ -n "$(snap "$b")" ] || { echo "В загрузке $b снимка нет (драйвер старше 25.10 или lab_boot_snap=0)"; exit 1; }
    lines "$b" | sed -E 's/^nouveau [^ ]+ clk: //'
else
    a="$(snap "$1")"; b="$(snap "$2")"
    [ -n "$a" ] && [ -n "$b" ] || { echo "Нет снимка в одном из источников ($1, $2)"; exit 1; }
    join <(echo "$a" | sort) <(echo "$b" | sort) | awk -v A="$1" -v B="$2" '
        { n++ }
        $2 != $3 { printf "%s  %s: %s  %s: %s%s\n", $1, A, $2, B, $3, ($1 == "020008" || $1 == "020400") ? "  (датчик температуры)" : ""; d++; if ($1 != "020008" && $1 != "020400") r++ }
        END { printf "сравнено %d регистров: различаются %d, без датчика температуры — %d\n", n, d+0, r+0 }'
fi
