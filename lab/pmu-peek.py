#!/usr/bin/env python3
# ТОЛЬКО ЧТЕНИЕ (22.11, после опыта 114): состояние PMU, когда поток регулятора повис в ожидании ответа прошивки.
# Читает регистры через окно BAR0 (resource0), ничего не пишет. Что смотрим (nouveau pmu/gt215.c):
#   0x10a4a0 / 0x10a4b0 — очередь «драйвер -> прошивка»: голова (пишет драйвер) / хвост (двигает прошивка, когда прочла).
#                         Голова != хвост — прошивка не забрала сообщение: ВСТАЛА ПРОШИВКА.
#   0x10a4c8 / 0x10a4cc — очередь «прошивка -> драйвер»: голова (пишет прошивка) / хвост (двигает драйвер, когда прочёл).
#                         Голова != хвост — ответ лежит, а драйвер его не забрал: ПОТЕРЯЛ NOUVEAU.
#   0x10a100 — управление микроконтроллером (бит 4 — остановлен); 0x10a008 / 0x10a01c — прерывания и их направление;
#   0x10a580 — кому сейчас отдан доступ к памяти данных PMU (1 — драйвер пишет, 2 — драйвер читает, 0 — свободно);
#   0x10a578 / 0x10a538 — счётчики PMU «все такты» / «графика» (наш процесс PERF): идут ли.
#   sudo python3 -I lab/pmu-peek.py            — два снимка с разницей 1 с
import mmap, struct, subprocess, time, os, sys
bdf = subprocess.run("lspci -D -d 10de: | grep -E 'VGA|3D' | head -n1 | cut -d' ' -f1", shell=True,
                     capture_output=True, text=True).stdout.strip()
fd = os.open(f"/sys/bus/pci/devices/{bdf}/resource0", os.O_RDONLY | os.O_SYNC)
m = mmap.mmap(fd, 0x200000, mmap.MAP_SHARED, mmap.PROT_READ)
rd = lambda a: struct.unpack_from("<I", m, a)[0]
R = [(0x10a100, "CPUCTL"), (0x10a4a0, "в PMU: голова"), (0x10a4b0, "в PMU: хвост"), (0x10a4c8, "из PMU: голова"),
     (0x10a4cc, "из PMU: хвост"), (0x10a008, "прерывания"), (0x10a01c, "направление прер."), (0x10a580, "доступ к данным"),
     (0x10a578, "счётчик: все такты"), (0x10a538, "счётчик: графика")]
snaps = []
for k in range(2):
    snaps.append({a: rd(a) for a, _ in R})
    if k == 0:
        time.sleep(1)
print(f"PMU {bdf}:")
for a, n in R:
    v0, v1 = snaps[0][a], snaps[1][a]
    print(f"  {a:#08x} {n:20s} {v0:08x} -> {v1:08x}{'  (меняется)' if v0 != v1 else ''}")
s = snaps[1]
print("остановлен" if s[0x10a100] & 0x10 else "микроконтроллер не остановлен (бит 4 = 0)")
print("очередь в PMU:", "ПУСТА — прошивка всё прочла" if s[0x10a4a0] == s[0x10a4b0] else "НЕ ПРОЧИТАНО прошивкой")
print("очередь из PMU:", "ПУСТА — драйвер всё забрал" if s[0x10a4c8] == s[0x10a4cc] else "ЛЕЖИТ ОТВЕТ, драйвер не забрал")
